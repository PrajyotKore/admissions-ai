import abc
import uuid
import random
from typing import Any
from datetime import datetime, timezone


class VoiceSessionResult:
    def __init__(
        self,
        provider_call_id: str,
        status: str,
        outcome: str | None,
        duration_seconds: int,
        cost_cents: int,
        is_synthetic: bool,
        transcript: str | None = None,
        summary: str | None = None,
        extracted_fields: dict | None = None,
        next_action: str | None = None,
        error: str | None = None,
    ):
        self.provider_call_id = provider_call_id
        self.status = status
        self.outcome = outcome
        self.duration_seconds = duration_seconds
        self.cost_cents = cost_cents
        self.is_synthetic = is_synthetic
        self.transcript = transcript
        self.summary = summary
        self.extracted_fields = extracted_fields or {}
        self.next_action = next_action
        self.error = error


class VoiceProviderInterface(abc.ABC):
    @abc.abstractmethod
    def initiate_call(self, to_phone: str, lead_data: dict, org_name: str, approved_knowledge: str) -> VoiceSessionResult:
        """Initiate outbound voice call."""
        pass

    @abc.abstractmethod
    def get_status(self, provider_call_id: str) -> dict:
        """Fetch status of active or finished call."""
        pass

    @abc.abstractmethod
    def verify_webhook(self, headers: dict, body: bytes) -> bool:
        """Verify webhook signature/authenticity."""
        pass


class MockVoiceProvider(VoiceProviderInterface):
    """
    Mock voice provider for testing & compliance-safe local development.
    CRITICAL: All calls generated by this provider have is_synthetic = True.
    Simulates real call lifecycles, structured state-driven conversation flows,
    and realistic outcomes.
    """
    def __init__(self):
        self.provider_name = "mock"

    def initiate_call(self, to_phone: str, lead_data: dict, org_name: str, approved_knowledge: str) -> VoiceSessionResult:
        call_id = f"mock-call-{uuid.uuid4().hex[:12]}"
        student_name = lead_data.get("name", "Student")
        course = lead_data.get("preferred_course", "their preferred course")

        # Deterministic simulation based on lead phone or random seed
        outcomes_distribution = [
            ("Interested", 0.40),
            ("Callback Requested", 0.20),
            ("Appointment Booked", 0.15),
            ("Not Interested", 0.10),
            ("No Answer", 0.10),
            ("Busy", 0.05),
        ]
        r = random.random()
        cumulative = 0.0
        outcome = "Interested"
        for out, prob in outcomes_distribution:
            cumulative += prob
            if r <= cumulative:
                outcome = out
                break

        if outcome in ("No Answer", "Busy"):
            return VoiceSessionResult(
                provider_call_id=call_id,
                status="no_answer" if outcome == "No Answer" else "busy",
                outcome=outcome,
                duration_seconds=random.randint(10, 25),
                cost_cents=0,
                is_synthetic=True,
                error=f"Line returned {outcome.lower()}",
            )

        # Build realistic structured transcript based on conversational script
        duration = random.randint(75, 240)
        cost_cents = int((duration / 60) * 15) # 15 cents/min synthetic rate

        transcript = (
            f"AI Assistant: Hello {student_name}, this is Priya from {org_name}. "
            f"I'm an automated admissions assistant following up on your enquiry about {course}. Do you have two minutes to speak?\n"
            f"{student_name}: Yes, go ahead.\n"
            f"AI Assistant: Great! I see you are looking for admissions guidance. "
            f"Based on our approved admissions criteria, what was your recent academic score or percentage?\n"
            f"{student_name}: I scored around 78% in my exams.\n"
            f"AI Assistant: That's a strong profile. For {course}, our partner institutions have seats open for the upcoming academic session.\n"
        )

        if outcome == "Appointment Booked":
            transcript += (
                f"AI Assistant: Would you like to book an in-depth counselling session with our senior educational advisor tomorrow at 11:00 AM?\n"
                f"{student_name}: Yes, that works for me. Please schedule it.\n"
                f"AI Assistant: Confirmed! We have reserved your appointment. Have a great day!\n"
            )
            summary = f"Student {student_name} confirmed interest in {course}. Marks: ~78%. Scheduled counselling appointment for tomorrow."
            next_action = "Prepare academic brochures for booked appointment"
            extracted = {"academic_marks": 78.0, "appointment_requested": True}

        elif outcome == "Callback Requested":
            transcript += (
                f"{student_name}: Actually I am traveling right now. Could you please call me back tomorrow evening?\n"
                f"AI Assistant: Certainly! I will schedule a follow-up for tomorrow evening. Thank you!\n"
            )
            summary = f"Student was traveling; requested follow-up call tomorrow evening regarding {course}."
            next_action = "Call back tomorrow evening"
            extracted = {"callback_requested": True}

        elif outcome == "Not Interested":
            transcript += (
                f"{student_name}: Actually I have already taken admission somewhere else, so I am not interested.\n"
                f"AI Assistant: Thank you for letting us know, and best of luck with your studies. Goodbye!\n"
            )
            summary = "Student already enrolled in another institution; not interested in further admissions assistance."
            next_action = "Mark lead as Not Interested; archive enquiry"
            extracted = {"enrolled_elsewhere": True}

        else: # Interested
            transcript += (
                f"{student_name}: What are the fee ranges for this course?\n"
                f"AI Assistant: Annual tuition fees generally range between ₹3,00,000 to ₹5,00,000 depending on the university. "
                f"I will assign your file to our senior counsellor who will email you the official fee breakup.\n"
                f"{student_name}: Perfect, please do that.\n"
            )
            summary = f"Student confirmed interest in {course}. Discussed fee parameters. Ready for counsellor follow-up."
            next_action = "Counsellor to send detailed fee sheet and syllabus"
            extracted = {"academic_marks": 78.0, "interest_confirmed": True}

        return VoiceSessionResult(
            provider_call_id=call_id,
            status="completed",
            outcome=outcome,
            duration_seconds=duration,
            cost_cents=cost_cents,
            is_synthetic=True,
            transcript=transcript,
            summary=summary,
            extracted_fields=extracted,
            next_action=next_action,
        )

    def get_status(self, provider_call_id: str) -> dict:
        return {"provider_call_id": provider_call_id, "status": "completed", "is_synthetic": True}

    def verify_webhook(self, headers: dict, body: bytes) -> bool:
        return True


def get_voice_provider(provider_type: str = "mock") -> VoiceProviderInterface:
    if provider_type == "mock":
        return MockVoiceProvider()
    # Real provider integration requires explicit compliance checks & valid telephony credentials
    raise ValueError(f"Provider {provider_type} is not configured or lacks compliance verification.")
